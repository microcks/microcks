<script lang="ts" module>
  import type { CatalogExample } from './types.js';

  export type ProposalStatus = 'pending' | 'accepted' | 'rejected';
  export interface Item {
    example: CatalogExample;
    status: ProposalStatus;
    edited: boolean;
    expanded: boolean;
    editing: boolean;
    draftName: string;
    draftBody: string;
  }

  export const fresh = (example: CatalogExample, expanded = false): Item => ({
    example,
    status: 'pending',
    edited: false,
    expanded,
    editing: false,
    draftName: example.name,
    draftBody: example.response.body
  });

  export function validateDraft(name: string, body: string): string | undefined {
    if (!name.trim()) return 'The example name is required.';
    try {
      JSON.parse(body);
    } catch {
      return 'The response body must be valid JSON.';
    }
    return undefined;
  }
</script>

<script lang="ts">
  import { tick } from 'svelte';
  import { Button, Icon } from '@microcks/deep-ink';
  import ExchangeCard from './ExchangeCard.svelte';
  import ExchangePair from './ExchangePair.svelte';
  import { exampleUrlPath, paramLines } from './snippets.js';

  interface Props {
    item: Item;
    method: string;
    pathTemplate: string;
    mockBase: string;
    served: CatalogExample[];
    onpatch: (fn: (i: Item) => Item) => void;
    onaccept: (edited: boolean) => void;
    onreject: () => void;
    onundo: () => void;
  }

  let { item, method, pathTemplate, mockBase, served, onpatch, onaccept, onreject, onundo }: Props = $props();
  const uid = $props.id();
  const e = $derived(item.example);
  const pending = $derived(item.status === 'pending');
  const rejected = $derived(item.status === 'rejected');
  const sameParams = (a: Record<string, string>, b: Record<string, string>) => JSON.stringify(Object.entries(a).sort()) === JSON.stringify(Object.entries(b).sort());
  const twin = $derived(rejected ? undefined : served.find((s) => s.id !== e.id && sameParams(s.request.params, e.request.params)));
  const conflict = $derived(twin ? `Same request criteria as “${twin.name}”: the mock would keep serving the first one.` : undefined);
  const draftError = $derived(item.editing ? validateDraft(item.draftName, item.draftBody) : undefined);
  const url = $derived(new URL(`${mockBase}${exampleUrlPath(pathTemplate, e.request.params)}`));
  const reqLine = $derived(`${method} ${url.pathname}${url.search}`);
  const reqText = $derived(`${reqLine} HTTP/1.1\nHost: ${url.host}\nAccept: application/json${e.request.body ? '\nContent-Type: application/json' : ''}`);
  const sub = $derived(Object.entries(e.request.params).map(([k, v]) => `${k}=${v}`).join(' · '));
  const open = $derived(item.expanded && !item.editing && !rejected);
  let root: HTMLElement | undefined = $state();

  async function focusAfter(sel: string) {
    await tick();
    root?.querySelector<HTMLElement>(sel)?.focus();
  }
</script>

<article bind:this={root} aria-label={`${e.name}, ${item.status}`} class="proposal" data-status={item.status}>
  <div class="proposal-head">
    <button type="button" class="proposal-toggle" aria-expanded={item.expanded && !rejected} onclick={() => onpatch((i) => ({ ...i, expanded: !i.expanded }))}>
      <Icon name="chevron" size={14} class="proposal-chevron" />
      <span class="proposal-code">{e.response.status}</span>
      <span class="proposal-title"><span class="proposal-name">{e.name}</span> <span class="proposal-sub">{sub}</span></span>
    </button>

    {#if pending && !item.editing}
      <span class="proposal-state" data-tone="warning"><Icon name="spark" size={13} />Generated by AI, review needed</span>
    {/if}
    {#if item.status === 'accepted'}
      <span class="proposal-state" data-tone="success">
        <Icon name="check" size={13} />Accepted
        <span class="proposal-ai-tag"><Icon name="spark" size={9} />AI</span>
        {#if item.edited}<span class="proposal-edited">edited</span>{/if}
      </span>
    {/if}
    {#if rejected}<span class="proposal-state" data-tone="muted"><Icon name="cross" size={13} />Rejected</span>{/if}

    <span class="proposal-actions">
      {#if pending && !item.editing}
        <Button size="sm" variant="primary" data-act="accept" aria-label={`Accept ${e.name}`} onclick={() => { onaccept(false); focusAfter('[data-act=undo]'); }}>Accept</Button>
        <Button size="sm" data-act="edit" aria-label={`Edit ${e.name}`} onclick={() => { onpatch((i) => ({ ...i, editing: true, expanded: true, draftName: i.example.name, draftBody: i.example.response.body })); focusAfter('input'); }}>Edit</Button>
        <Button size="sm" variant="link" aria-label={`Reject ${e.name}`} onclick={() => { onreject(); focusAfter('[data-act=undo]'); }}>Reject</Button>
      {/if}
      {#if !pending}
        <Button size="sm" variant="link" data-act="undo" aria-label={`Undo for ${e.name}`} onclick={() => { onundo(); focusAfter('[data-act=accept]'); }}>Undo</Button>
      {/if}
    </span>
  </div>

  {#if conflict}<p class="proposal-conflict" role="note"><Icon name="warning" size={13} />{conflict}</p>{/if}

  {#if open}
    <div class="proposal-body">
      <ExchangePair>
        {#snippet request()}
          <ExchangeCard
            size="sm"
            title="Request"
            label={`Request of ${e.name}`}
            blocks={[
              { label: 'Request line and headers', text: reqText, tone: 'secondary' },
              ...(Object.keys(e.request.params).length ? [{ label: 'Parameters', text: paramLines(pathTemplate, e.request.params), tone: 'params' as const }] : []),
              ...(e.request.body ? [{ label: 'Request body', text: e.request.body }] : [])
            ]}
          />
        {/snippet}
        {#snippet response()}
          <ExchangeCard size="sm" title="Response" label={`Response of ${e.name}`} status={`${e.response.status} · ${e.response.contentType}`} blocks={[{ label: 'Response body', text: e.response.body, grow: true }]} />
        {/snippet}
      </ExchangePair>
    </div>
  {/if}

  {#if item.editing}
    <div class="proposal-edit proposal-body">
      <div class="proposal-edit-row">
        <div class="proposal-edit-field" data-size="name">
          <label class="section-label" for={`${uid}-name`}>Example name</label>
          <input id={`${uid}-name`} class="input" value={item.draftName} oninput={(ev) => onpatch((i) => ({ ...i, draftName: ev.currentTarget.value }))} />
        </div>
        <div class="proposal-edit-field" data-size="request">
          <span class="section-label" id={`${uid}-req`}>Request</span>
          <span class="proposal-edit-request" aria-labelledby={`${uid}-req`} role="group">{reqLine}</span>
        </div>
      </div>
      <div class="proposal-edit-field">
        <label class="section-label" for={`${uid}-body`}>Response body · {e.response.contentType}</label>
        <textarea id={`${uid}-body`} class="input" data-mono spellcheck="false" rows={Math.min(18, item.draftBody.split('\n').length + 1)} value={item.draftBody} aria-invalid={draftError ? true : undefined} aria-describedby={draftError ? `${uid}-err` : undefined} oninput={(ev) => onpatch((i) => ({ ...i, draftBody: ev.currentTarget.value }))}></textarea>
        {#if draftError}<span id={`${uid}-err`} class="proposal-edit-error"><Icon name="cross" size={13} />{draftError}</span>{/if}
      </div>
      <div class="proposal-edit-actions">
        <Button size="sm" variant="primary" disabled={Boolean(draftError)} onclick={() => { onaccept(true); focusAfter('[data-act=undo]'); }}>Apply and accept</Button>
        <Button size="sm" onclick={() => { onpatch((i) => ({ ...i, editing: false, draftName: i.example.name, draftBody: i.example.response.body })); focusAfter('[data-act=edit]'); }}>Cancel edit</Button>
      </div>
    </div>
  {/if}
</article>
