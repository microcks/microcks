<script lang="ts">
  import type { Snippet } from 'svelte';
  import Icon from './Icon.svelte';

  interface Props {
    tone?: 'info' | 'success' | 'warning' | 'danger' | 'ai';
    title?: string;
    live?: 'polite' | 'assertive' | false;
    variant?: 'filled' | 'outline';
    size?: 'md' | 'sm';
    class?: string;
    children?: Snippet;
    actions?: Snippet;
  }

  let { tone = 'info', title, live = false, variant = 'filled', size = 'md', class: className, children, actions }: Props = $props();

  const ICON = { info: 'info', success: 'check', warning: 'warning', danger: 'cross', ai: 'spark' } as const;
  const TONE_WORD = { info: 'Information', success: 'Success', warning: 'Warning', danger: 'Error', ai: 'AI suggestion' } as const;
  const titleId = $props.id();
  const heading = $derived(title ?? (tone === 'ai' ? 'Generated by AI, review needed' : undefined));
  const role = $derived(live === 'assertive' ? 'alert' : live === 'polite' ? 'status' : variant === 'outline' ? 'note' : undefined);
</script>

<div
  class={['callout', className]}
  data-tone={tone}
  data-variant={variant === 'outline' ? 'outline' : undefined}
  data-size={size === 'sm' ? 'sm' : undefined}
  {role}
  aria-labelledby={heading ? titleId : undefined}
>
  <Icon name={ICON[tone]} size={18} label={heading ? undefined : TONE_WORD[tone]} />
  <div class="callout-body">
    {#if heading}<p class="callout-title" id={titleId}>{heading}</p>{/if}
    {#if children}<div class="callout-content">{@render children()}</div>{/if}
    {#if actions}<div class="callout-actions">{@render actions()}</div>{/if}
  </div>
</div>
